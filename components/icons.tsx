export type IconName = keyof typeof GRIDS;

/** Exported for the test that keeps every grid 12×12. */
export const ICON_GRIDS: Record<IconName, readonly string[]> = GRIDS;

export function Icon({ name, className = "size-5" }: { name: IconName; className?: string }) {
  return (
    <svg
      viewBox={`0 0 ${PIXEL_SIZE} ${PIXEL_SIZE}`}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden
      className={className}
    >
      <path d={pixelPath(GRIDS[name], "#")} />
    </svg>
  );
}
