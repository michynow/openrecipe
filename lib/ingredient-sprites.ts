/** Lower-case, diacritics folded. ł has no combining form, so it goes by hand. */
export function foldPolish(text: string): string {
  return text
    .toLowerCase()
    .replace(/ł/g, "l")
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "");
}

export function spriteFor(item: string): SpriteName {
  const name = foldPolish(item);
  let best: { sprite: SpriteName; at: number; length: number } | null = null;

  for (const [sprite, stems] of STEMS) {
    for (const stem of stems) {
      // Start of a word: beginning of the string or after a non-letter.
      const match = new RegExp(`(^|[^\\p{L}])${stem}`, "u").exec(name);
      if (!match) continue;
      const at = match.index + match[1].length;
      if (!best || at < best.at || (at === best.at && stem.length > best.length)) {
        best = { sprite, at, length: stem.length };
      }
    }
  }

  return best?.sprite ?? "pot";
}
